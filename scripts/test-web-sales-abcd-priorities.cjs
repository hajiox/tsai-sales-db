const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (m, f) => m._compile(ts.transpileModule(fs.readFileSync(f, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, f);
const { buildPriorities } = require('../lib/web-sales-abcd/priorities.ts');
const item = (key, rank = 'A', access = 100) => ({ key, name: key, rank, access });
const financial = (key, rank, profit = 100, quality = '推計') => ({ key, rank, profit, quality, sales: 1000 });
const items = [item('small-loss'), item('big-loss'), item('unknown'), item('partial'), item('grow'), item('page', 'B'), item('hold', '保留')];
const finance = { items: [financial('small-loss', '赤字', -10), financial('big-loss', '赤字', -100), financial('partial', '保留', 100, '費用一部'), financial('grow', 'C'), financial('page', 'B'), financial('hold', '保留')] };
const result = buildPriorities(items, finance);
assert.equal(result[0].id, 'loss');
assert.deepEqual(result[0].products.map(p => p.key), ['big-loss', 'small-loss']);
assert.equal(result[0].count, 2);
assert.deepEqual(result.find(p => p.id === 'data').products.map(p => p.key), ['unknown', 'partial']);
assert.deepEqual(result.find(p => p.id === 'growth').products.map(p => p.key), ['grow']);
assert.deepEqual(result.find(p => p.id === 'page').products.map(p => p.key), ['page']);
assert.equal(result.find(p => p.id === 'traffic').count, 1);
const missing = buildPriorities(items);
assert.equal(missing[0].id, 'data');
assert.equal(missing[0].count, items.length);
assert.equal(missing[0].products.length, 3);
assert.equal(missing.some(p => p.id === 'growth'), false);
assert.equal(buildPriorities([item('loss', 'B')], { items: [financial('loss', '赤字', -1)] }).some(p => p.id === 'page'), false);
console.log('PASS ABCD priorities: loss order, missing/partial costs, growth eligibility, counts, examples, page exclusion');
