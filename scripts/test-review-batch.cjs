const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,f);
const {batchEntryStatus}=require('../lib/recipe-reviews/batch-status.ts');
const e={recipeId:'r',name:'商品',jobId:'c',reason:null};
const c={id:'c',status:'completed'},a={id:'a',idempotency_key:'reviews-analysis:c',status:'running'};
assert.equal(batchEntryStatus({...e,jobId:null,reason:'未設定'},[]).state,'unmapped');
assert.equal(batchEntryStatus(e,[]).state,'attention');
assert.equal(batchEntryStatus(e,[{...c,status:'queued'}]).state,'active');
assert.equal(batchEntryStatus(e,[c,a]).state,'active');
assert.equal(batchEntryStatus(e,[{...c,status:'needs_review'},{...a,status:'completed'}]).state,'attention');
assert.equal(batchEntryStatus(e,[c,{...a,status:'failed'}]).state,'attention');
assert.equal(batchEntryStatus(e,[c,{...a,status:'completed'}]).state,'completed');
assert.equal(batchEntryStatus(e,[c]).message,'収集完了（分析対象なし）');
console.log('PASS batch progress: collection, analysis, partial, failure, unmapped');
const {batchEntryDetails}=require('../lib/recipe-reviews/batch-status.ts');
const partial=[{job_id:'c',result:{sources:[{channel:'base',productKey:'1',status:'partial',count:2,message:'評価のみ未保存'}]}}];
const pending={...c,parameters:{directAnalysisPending:true}};
assert.equal(batchEntryDetails(e,[pending],partial,'ネット専用').category,'analysis_pending');
assert.equal(batchEntryDetails(e,[pending],partial,'ネット専用').sources[0].count,2);
assert.equal(batchEntryDetails(e,[pending],partial,'終売').category,'excluded');
assert.equal(batchEntryDetails(e,[{...pending,status:'waiting_for_user'}],partial,'ネット専用').category,'user_wait');
assert.equal(batchEntryDetails(e,[{...pending,status:'running'}],partial,'終売').category,'active');
assert.equal(batchEntryDetails({...e,jobId:null},[],[],'ネット専用').category,'unmapped');
assert.equal(batchEntryDetails(e,[{...c,status:'failed'}],[],'ネット専用').category,'attention');
assert.equal(batchEntryDetails(e,[c,{...a,status:'waiting_for_user'}],[],'ネット専用').category,'user_wait');
console.log('PASS separate analysis, source coverage, excluded and operator waits');
